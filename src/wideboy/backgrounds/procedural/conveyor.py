class _ConveyorEffect(Effect):
    name = "conveyor"
    default_palette = "neon"
    tags = ("linear", "retro")

    def __call__(self, t: float, w: int, h: int, palette: Palette) -> np.ndarray:
        belt_h = 4
        cog_r = 6
        speed = 40.0
        spacing = 120.0

        dim = np.array(palette.dim, dtype=np.uint8)
        colors = [
            dim,
            np.array(palette.primary, dtype=np.uint8),
            np.array(palette.secondary, dtype=np.uint8),
            np.array(palette.accent, dtype=np.uint8),
            np.array(palette.highlight, dtype=np.uint8),
        ]

        frame = np.zeros((h, w, 3), dtype=np.uint8)
        frame[:, :] = dim

        mid = h // 2
        belt1_y = mid - belt_h - 2
        belt2_y = h - belt_h

        belt_color = np.array([50, 50, 50], dtype=np.uint8)
        frame[belt1_y : belt1_y + belt_h, :] = belt_color
        frame[belt2_y : belt2_y + belt_h, :] = belt_color

        scroll = t * speed
        for by, direction in [(belt1_y, -1), (belt2_y, 1)]:
            offset = int(scroll * direction)
            for x in range(0, w, 8):
                px = (x + offset) % w
                if 0 <= px < w:
                    frame[by, px] = colors[4]

        for by in [belt1_y, belt2_y]:
            cy = by + belt_h // 2
            for cx in [cog_r, w - cog_r - 1]:
                for dy in range(-cog_r, cog_r + 1):
                    for dx in range(-cog_r, cog_r + 1):
                        dist = (dx * dx + dy * dy) ** 0.5
                        if dist <= cog_r:
                            py, px = cy + dy, cx + dx
                            if 0 <= py < h and 0 <= px < w:
                                angle = math.atan2(dy, dx) + t * 2
                                tooth = int((angle * 4 / math.pi) % 2)
                                if dist < cog_r * 0.4:
                                    frame[py, px] = colors[1]
                                elif tooth and dist > cog_r * 0.6:
                                    frame[py, px] = colors[3]
                                else:
                                    frame[py, px] = np.array([80, 80, 80], dtype=np.uint8)

        objs = _CONVEYOR_OBJS
        n = len(objs)

        for i in range(n):
            base_x = i * spacing
            x1 = (base_x - scroll) % (spacing * n)
            if x1 > w + 30:
                x1 -= spacing * n
            oh = objs[i].shape[0]
            draw_obj(frame, objs[i], int(x1), belt1_y - oh, colors, belt1_y)

        for i in range(n):
            base_x = i * spacing
            x2 = (base_x + scroll) % (spacing * n)
            if x2 > w + 30:
                x2 -= spacing * n
            obj = objs[(i + 5) % n]
            oh = obj.shape[0]
            draw_obj(frame, obj, int(x2), belt2_y - oh, colors, belt2_y)

        return frame


conveyor = _ConveyorEffect()
